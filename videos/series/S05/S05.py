# ---------------------------------------------------------------- checks
# d'Alembert: a_n = n^2/5^n, a_n/a_{n+1} = 5 n^2/(n+1)^2 -> 5
A1 = n ** 2 / 5 ** n
assert sp.simplify(A1 / A1.subs(n, n + 1) - 5 * n ** 2 / (n + 1) ** 2) == 0
assert ws.radius(A1) == 5
# the reason: ratio test on |a_n x^n| gives |x|/R
assert ws.lim((A1.subs(n, n + 1) / A1)) == sp.Rational(1, 5)
# Cauchy-Hadamard: a_n = (n/(3n+1))^n, n-th root = n/(3n+1) -> 1/3, R = 3
A2 = (n / (3 * n + 1)) ** n
assert ws.lim(n / (3 * n + 1)) == sp.Rational(1, 3)
assert ws.root(A2) == sp.Rational(1, 3)
# shift + even powers: Σ (x-2)^{2n}/9^n = Σ t^n/9^n with t = (x-2)^2: R_t = 9, |x-2| < 3, center 2
assert ws.radius(1 / 9 ** n) == 9
assert sp.solve_univariate_inequality((X - 2) ** 2 < 9, X, relational=False) == sp.Interval.open(-1, 5)
# R = ∞: a_n = 1/n!, a_n/a_{n+1} = n+1
assert sp.simplify(sp.combsimp((1 / sp.factorial(n)) / (1 / sp.factorial(n + 1))) - (n + 1)) == 0
assert ws.radius(1 / sp.factorial(n)) == sp.oo

# exam 23A-C-Q3a
