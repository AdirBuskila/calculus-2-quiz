assert r"x^n\,\frac{1}{2^n+3^n}" in EX["question"]
C = 1 / (2 ** n + 3 ** n)
assert ws.lim((2 ** n + 3 ** n) ** (1 / n)) == 3
assert ws.lim((1 + sp.Rational(2, 3) ** n) ** (1 / n)) == 1
assert ws.root(C) == sp.Rational(1, 3)
R = 1 / ws.root(C)
assert R == 3 and ws.radius(C) == 3                      # d'Alembert agrees
# endpoints: x = 3 -> 3^n/(2^n+3^n) -> 1; x = -3 -> |term| -> 1: both diverge
assert ws.lim(3 ** n * C) == 1
assert sp.simplify(3 ** n * C - 1 / (1 + sp.Rational(2, 3) ** n)) == 0
