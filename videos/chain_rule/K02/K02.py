# ---------------------------------------------------------------- verified math
T = x**3 * y
assert sp.diff(T, x) == 3 * x**2 * y and sp.diff(T, y) == x**3
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T), x) - 3 * x**2 * y * gp(T))
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T), y) - x**3 * gp(T))
assert sp.simplify(sp.diff(sp.sin(T), x) - 3 * x**2 * y * sp.cos(x**3 * y)) == 0          # the g = sin check
# the two wrong versions really differ from z_x (for g = sin): g instead of g', and a changed argument
assert sp.simplify(sp.diff(sp.sin(T), x) - 3 * x**2 * y * sp.sin(T)) != 0
assert sp.simplify(sp.diff(sp.sin(T), x) - 3 * x**2 * y * sp.cos(3 * x**2 * y)) != 0

# exam 24S-A-Q4b: f = ln(x + 1/y), points with grad f = (1, -16/9), tangent planes there
F = sp.log(x + 1 / y)
TE = x + 1 / y
assert sp.diff(TE, x) == 1 and sp.diff(TE, y) == -1 / y**2
FX, FY = sp.diff(F, x), sp.diff(F, y)
assert sp.simplify(FX - 1 / TE) == 0 and sp.simplify(FY - (-1 / y**2) / TE) == 0
SOL = sp.solve([sp.Eq(FX, 1), sp.Eq(FY, sp.Rational(-16, 9))], [x, y], dict=True)
PTS = sorted([(s[x], s[y]) for s in SOL], key=lambda p: p[1], reverse=True)
assert PTS == [(sp.Rational(-1, 3), sp.Rational(3, 4)), (sp.Rational(7, 3), sp.Rational(-3, 4))]
for x0, y0 in PTS:
    assert TE.subs({x: x0, y: y0}) == 1 and F.subs({x: x0, y: y0}) == 0          # in the domain, f = ln 1 = 0
PL = []
for x0, y0 in PTS:
    plane = F.subs({x: x0, y: y0}) + FX.subs({x: x0, y: y0}) * (x - x0) + FY.subs({x: x0, y: y0}) * (y - y0)
    PL.append(sp.expand(plane))
assert PL[0] == x - sp.Rational(16, 9) * y + sp.Rational(5, 3)
assert PL[1] == x - sp.Rational(16, 9) * y - sp.Rational(11, 3)

