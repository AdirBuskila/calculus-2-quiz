# ---------------------------------------------------------------- 22A-A-Q3b
F = y**3 + x * z + y**2 + sp.exp(z) - 3
PT = {x: 1, y: 1, z: 0}
assert F.subs(PT) == 0
FX, FY, FZ = (sp.diff(F, s) for s in (x, y, z))
assert (FX, FY, FZ) == (z, 3 * y**2 + 2 * y, x + sp.exp(z))
assert (FX.subs(PT), FY.subs(PT), FZ.subs(PT)) == (0, 5, 2)
ZX, ZY = -FX.subs(PT) / FZ.subs(PT), -FY.subs(PT) / FZ.subs(PT)
assert (ZX, ZY) == (0, sp.Rational(-5, 2))
PLANE = sp.expand(2 * (0 + ZX * (x - 1) + ZY * (y - 1)))       # 2z = ...
assert PLANE == 5 - 5 * y                                       # 2z = 5 - 5y  <=>  5y + 2z - 5 = 0
def zf(a, b):
    return mp.findroot(lambda s: b**3 + a * s + b**2 + mp.e**s - 3, 0)
h = mp.mpf("1e-6")
assert abs((zf(1 + h, 1) - zf(1 - h, 1)) / (2 * h) - 0) < 1e-6
assert abs((zf(1, 1 + h) - zf(1, 1 - h)) / (2 * h) + 2.5) < 1e-6

# ---------------------------------------------------------------- 24A-A-Q1b
G = 2 * sp.exp(-x**2) + sp.exp(-3 * y**2)
GX, GY = sp.diff(G, x), sp.diff(G, y)
assert sp.simplify(GX - (-4 * x * sp.exp(-x**2))) == 0 and sp.simplify(GY - (-6 * y * sp.exp(-3 * y**2))) == 0
G0 = (GX.subs({x: 1, y: 0}), GY.subs({x: 1, y: 0}))
assert sp.simplify(G0[0] + 4 / sp.E) == 0 and G0[1] == 0
NG = sp.sqrt(G0[0]**2 + G0[1]**2)
assert sp.simplify(NG - 4 / sp.E) == 0
assert (sp.simplify(G0[0] / NG), sp.simplify(G0[1] / NG)) == (-1, 0)

# ---------------------------------------------------------------- 22A-B-Q1a
L = sp.log(x**2 + y**2 + z**2)
T = x**2 + y**2 + z**2
P3 = {x: 1, y: 2, z: 1}
assert T.subs(P3) == 6
LG = [sp.diff(L, s).subs(P3) for s in (x, y, z)]
for s, val in zip((x, y, z), LG):
    assert sp.simplify(sp.diff(L, s) - 2 * s / T) == 0               # (1/t) * t_s, t_s = 2s
assert LG == [sp.Rational(1, 3), sp.Rational(2, 3), sp.Rational(1, 3)]
NL = sp.sqrt(sum(c**2 for c in LG))
assert sp.simplify(NL - sp.sqrt(6) / 3) == 0
assert [sp.simplify(c / NL - d / sp.sqrt(6)) for c, d in zip(LG, (1, 2, 1))] == [0, 0, 0]

