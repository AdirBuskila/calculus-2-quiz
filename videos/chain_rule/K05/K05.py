# ---------------------------------------------------------------- verified math
T = x + y**2
assert (sp.diff(T, x), sp.diff(T, y), sp.diff(T, y, 2), sp.diff(T, x, y)) == (1, 2 * y, 2, 0)
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T), y) - 2 * y * gp(T))
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T), y, 2) - (2 * gp(T) + 4 * y**2 * gpp(T)))      # z_yy
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T), x, y) - 2 * y * gpp(T))                       # z_xy
# the general formulas on screen, for t = x + y^2 and a second inner function
for TT in (T, x**2 * y + sp.sin(y)):
    tx, ty = sp.diff(TT, x), sp.diff(TT, y)
    w.for_all_g(lambda g, gp, gpp: sp.diff(g(TT), x, 2) - (gpp(TT) * tx**2 + gp(TT) * sp.diff(TT, x, 2)))
    w.for_all_g(lambda g, gp, gpp: sp.diff(g(TT), x, y) - (gpp(TT) * tx * ty + gp(TT) * sp.diff(TT, x, y)))
# dropping g' t_yy is wrong here (t_yy = 2 != 0)
assert sp.simplify(sp.diff(sp.sin(T), y, 2) - 4 * y**2 * (-sp.sin(T))) != 0

# exam 22A-B-Q3b: F = z^3 - 3xyz - 4, point (2, 1, -2)
F = z**3 - 3 * x * y * z - 4
PT = {x: 2, y: 1, z: -2}
assert F.subs(PT) == 0
FZ = sp.diff(F, z)
assert FZ == 3 * z**2 - 3 * x * y and FZ.subs(PT) == 6
# differentiate the identity F(x, y, z(x,y)) = 0, with z a function
Zf = sp.Function("Z")(x, y)
E = F.subs(z, Zf)
ZX, ZY, ZXY = sp.symbols("ZX ZY ZXY")
rep = {sp.Derivative(Zf, x, y): ZXY, sp.Derivative(Zf, x): ZX, sp.Derivative(Zf, y): ZY}
EX = sp.expand(sp.diff(E, x) / 3)
assert sp.expand(EX.subs(rep) - (Zf**2 * ZX - y * Zf - x * y * ZX)) == 0            # z^2 z_x - yz - xy z_x = 0
EY = sp.expand(sp.diff(E, y) / 3)
assert sp.expand(EY.subs(rep) - (Zf**2 * ZY - x * Zf - x * y * ZY)) == 0
EXY = sp.expand(sp.diff(EX, y))
EXY_s = EXY.subs(rep)
assert sp.expand(EXY_s - (2 * Zf * ZY * ZX + Zf**2 * ZXY - Zf - y * ZY - x * ZX - x * y * ZXY)) == 0
at = lambda e: e.subs(Zf, -2).subs({x: 2, y: 1})
zx0 = sp.solve(at(EX.subs(rep)), ZX)[0]
zy0 = sp.solve(at(EY.subs(rep)), ZY)[0]
assert (zx0, zy0) == (-1, -2)
assert at(EX.subs(rep)).subs(ZX, sp.Symbol("q")).expand() == 2 * sp.Symbol("q") + 2      # 4q + 2 - 2q
TERMS = [at(2 * Zf * ZY * ZX).subs({ZX: -1, ZY: -2}), at(-Zf), at(-y * ZY).subs(ZY, -2), at(-x * ZX).subs(ZX, -1)]
assert TERMS == [-8, 2, 2, 2]
zxy0 = sp.solve(at(EXY_s).subs({ZX: zx0, ZY: zy0}), ZXY)[0]
assert zxy0 == 1
# numeric cross-check: solve F = 0 for z near -2 and take a central mixed difference
def zfun(a, b):
    return mp.findroot(lambda s: s**3 - 3 * a * b * s - 4, -2)
h = mp.mpf("1e-4")
num = (zfun(2 + h, 1 + h) - zfun(2 + h, 1 - h) - zfun(2 - h, 1 + h) + zfun(2 - h, 1 - h)) / (4 * h * h)
assert abs(num - 1) < 1e-5
assert abs((zfun(2 + h, 1) - zfun(2 - h, 1)) / (2 * h) - (-1)) < 1e-6

