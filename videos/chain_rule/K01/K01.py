# ---------------------------------------------------------------- verified math
T1 = x - y**3
assert sp.diff(T1, x) == 1 and sp.diff(T1, y) == -3 * y**2
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T1), x) - gp(T1))
w.for_all_g(lambda g, gp, gpp: sp.diff(g(T1), y) - gp(T1) * (-3 * y**2))

T2 = x * sp.exp(y)                                     # z = y^2 + g(x e^y)
assert sp.diff(T2, x) == sp.exp(y) and sp.diff(T2, y) == x * sp.exp(y)
w.for_all_g(lambda g, gp, gpp: sp.diff(y**2 + g(T2), x) - gp(T2) * sp.exp(y))                  # one route
w.for_all_g(lambda g, gp, gpp: sp.diff(y**2 + g(T2), y) - (2 * y + gp(T2) * x * sp.exp(y)))    # two routes

# exam 25A-A-Q5a: f = sqrt(x^2 + 2y) at (4, 10)
F = sp.sqrt(x**2 + 2 * y)
t = sp.Symbol("t", positive=True)
TE = x**2 + 2 * y
assert sp.diff(TE, x) == 2 * x and sp.diff(TE, y) == 2
assert sp.simplify(sp.diff(sp.sqrt(t), t) - 1 / (2 * sp.sqrt(t))) == 0
assert sp.simplify(sp.diff(F, x) - x / sp.sqrt(TE)) == 0 and sp.simplify(sp.diff(F, y) - 1 / sp.sqrt(TE)) == 0
P0 = {x: 4, y: 10}
assert TE.subs(P0) == 36
FX, FY = sp.diff(F, x).subs(P0), sp.diff(F, y).subs(P0)
assert (FX, FY) == (sp.Rational(2, 3), sp.Rational(1, 6))
NORM = sp.sqrt(FX**2 + FY**2)
assert sp.simplify(NORM - sp.sqrt(17) / 6) == 0
UDIR = (sp.simplify(FX / NORM), sp.simplify(FY / NORM))
assert sp.simplify(UDIR[0] - 4 / sp.sqrt(17)) == 0 and sp.simplify(UDIR[1] - 1 / sp.sqrt(17)) == 0
th = sp.Symbol("theta", real=True)                     # D_u f = |grad| cos(angle): the max over all unit u is |grad|
DU = FX * sp.cos(th) + FY * sp.sin(th)
assert abs(float(sp.maximum(DU, th, sp.Interval(0, 2 * sp.pi))) - float(NORM)) < 1e-12
# the trap: t_y = 1 instead of 2 gives f_y = 1/12, a wrong gradient
assert (sp.Rational(1, 2) / 6) == sp.Rational(1, 12)

