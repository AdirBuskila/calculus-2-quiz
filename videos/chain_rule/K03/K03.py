# ---------------------------------------------------------------- verified math
T = x - y**2
assert sp.diff(T, x) == 1 and sp.diff(T, y) == -2 * y
w.for_all_g(lambda g, gp, gpp: sp.diff(y * g(T), x) - y * gp(T))                          # no product rule
w.for_all_g(lambda g, gp, gpp: sp.diff(y * g(T), y) - (g(T) - 2 * y**2 * gp(T)))          # product rule
# forgetting g(t) really is wrong: for g = exp the term g(t) is never 0
assert sp.simplify(sp.diff(y * sp.exp(T), y) - (-2 * y**2 * sp.exp(T))) != 0
assert sp.simplify(sp.diff(y * sp.exp(T), y) - (sp.exp(T) - 2 * y**2 * sp.exp(T))) == 0   # the line shown on stage

# exam 24S-A-Q1a: f = y cos(xy), direction u (unit) with D_u f(1,0) = 1
F = y * sp.cos(x * y)
FX, FY = sp.diff(F, x), sp.diff(F, y)
assert sp.simplify(FX - (-y**2 * sp.sin(x * y))) == 0
assert sp.simplify(FY - (sp.cos(x * y) - x * y * sp.sin(x * y))) == 0
P0 = {x: 1, y: 0}
G0 = (FX.subs(P0), FY.subs(P0))
assert G0 == (0, 1)
a, b = sp.symbols("a b", real=True)
DIRS = sp.solve([sp.Eq(G0[0] * a + G0[1] * b, 1), sp.Eq(a**2 + b**2, 1)], [a, b], dict=True)
assert DIRS == [{a: 0, b: 1}]
# without the product-rule term cos(xy): f_y would be -xy sin(xy), 0 at (1,0), gradient 0 -> no direction at all
assert (-x * y * sp.sin(x * y)).subs(P0) == 0
# |grad f(1,0)| = 1: the value 1 is the maximum, reached only along the gradient
assert sp.sqrt(G0[0]**2 + G0[1]**2) == 1

