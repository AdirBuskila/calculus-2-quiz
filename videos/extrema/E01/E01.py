# ---------------------------------------------------------------- example 1: x^3 - 12x + y^2 - 2y
F1 = X**3 - 12 * X + Y**2 - 2 * Y
assert sp.expand(sp.diff(F1, X) - (3 * X**2 - 12)) == 0 and sp.expand(sp.diff(F1, Y) - (2 * Y - 2)) == 0
assert w.crit(F1) == [(-2, 1), (2, 1)]
assert w.kind(*w.hess(F1, (2, 1))[:3]) == "min" and w.kind(*w.hess(F1, (-2, 1))[:3]) == "saddle"

# ---------------------------------------------------------------- example 2: x^2 y - 4y + y^2 (a product = 0)
F2 = X**2 * Y - 4 * Y + Y**2
assert sp.diff(F2, X) == 2 * X * Y and sp.expand(sp.diff(F2, Y) - (X**2 + 2 * Y - 4)) == 0
assert w.crit(F2) == [(-2, 0), (0, 2), (2, 0)]
# dividing 2xy = 0 by y leaves x = 0 only, hence only (0, 2): the two points with y = 0 are lost
assert [p for p in w.crit(F2) if p[0] == 0] == [(0, 2)]

# ---------------------------------------------------------------- exam 22A-A-Q5b
Q = BANK["22A-A-Q5b"]
assert "xy^2-y^2-\\frac{x^2}{2}-2x+3" in Q["question"].replace(" ", "")
F = X * Y**2 - Y**2 - X**2 / 2 - 2 * X + 3
FX, FY = sp.diff(F, X), sp.diff(F, Y)
assert sp.expand(FX - (Y**2 - X - 2)) == 0 and sp.factor(FY) == 2 * Y * (X - 1)
s3 = sp.sqrt(3)
PTS = w.crit(F)
assert PTS == [(-2, 0), (1, -s3), (1, s3)]
H = {p: w.hess(F, p) for p in PTS}
assert w.same(sp.diff(F, X, 2), -1) and w.same(sp.diff(F, Y, 2), 2 * X - 2) and w.same(sp.diff(F, X, Y), 2 * Y)
assert H[(-2, 0)] == (-1, 0, -6, 6) and w.kind(*H[(-2, 0)][:3]) == "max"
assert H[(1, s3)] == (-1, 2 * s3, 0, -12) and H[(1, -s3)] == (-1, -2 * s3, 0, -12)
assert w.kind(*H[(1, s3)][:3]) == "saddle" and w.kind(*H[(1, -s3)][:3]) == "saddle"
assert w.val(F, (-2, 0)) == 5

