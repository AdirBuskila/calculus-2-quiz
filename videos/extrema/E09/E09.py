t = sp.symbols("t", real=True)
# ---------------------------------------------------------------- problem 1: x^3 - 12xy + 6y^2
F1 = X**3 - 12 * X * Y + 6 * Y**2
assert w.same(sp.diff(F1, X), 3 * X**2 - 12 * Y) and w.same(sp.diff(F1, Y), -12 * X + 12 * Y)
assert w.same((X**2 / 4).subs(X, X) - X, (X**2 - 4 * X) / 4) and sp.factor(X**2 - 4 * X) == X * (X - 4)
P1 = w.crit(F1)
assert P1 == [(0, 0), (4, 4)]
assert w.same(sp.diff(F1, X, 2), 6 * X) and w.same(sp.diff(F1, X, Y), -12) and w.same(sp.diff(F1, Y, 2), 12)
assert w.hess(F1, (0, 0)) == (0, -12, 12, -144) and w.kind(0, -12, 12) == "saddle"
assert w.hess(F1, (4, 4)) == (24, -12, 12, 144) and w.kind(24, -12, 12) == "min"
assert w.val(F1, (4, 4)) == -32 and w.val(F1, (0, 0)) == 0

# ---------------------------------------------------------------- problem 2: x^2 + 4xy + 2y^2 - 4y
F2 = X**2 + 4 * X * Y + 2 * Y**2 - 4 * Y
assert w.same(sp.diff(F2, X), 2 * X + 4 * Y) and w.same(sp.diff(F2, Y), 4 * X + 4 * Y - 4)
assert w.crit(F2) == [(2, -1)]
assert w.hess(F2, (2, -1)) == (2, 4, 4, -8) and w.kind(2, 4, 4) == "saddle" and w.val(F2, (2, -1)) == 2
# direct confirmation: along y = -1 the function rises, along the direction (-2, 1) it falls
assert w.same(F2.subs({X: 2 + t, Y: -1}) - 2, t**2)
assert w.same(F2.subs({X: 2 - 2 * t, Y: -1 + t}) - 2, -2 * t**2)

