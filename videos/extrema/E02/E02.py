# ---------------------------------------------------------------- the three model shapes
for g, k in ((X**2 + Y**2, "min"), (-X**2 - Y**2, "max"), (X**2 - Y**2, "saddle")):
    assert w.crit(g) == [(0, 0)] and w.kind(*w.hess(g, (0, 0))[:3]) == k

# ---------------------------------------------------------------- example 1: x^3 - 3x + y^2
F1 = X**3 - 3 * X + Y**2
assert w.crit(F1) == [(-1, 0), (1, 0)]
assert w.same(sp.diff(F1, X, 2), 6 * X) and w.same(sp.diff(F1, X, Y), 0) and w.same(sp.diff(F1, Y, 2), 2)
assert w.hess(F1, (1, 0)) == (6, 0, 2, 12) and w.kind(6, 0, 2) == "min" and w.val(F1, (1, 0)) == -2
assert w.hess(F1, (-1, 0)) == (-6, 0, 2, -12) and w.kind(-6, 0, 2) == "saddle"

# ---------------------------------------------------------------- example 2: x^2 + 4xy + y^2 (A>0, C>0, saddle)
F2 = X**2 + 4 * X * Y + Y**2
assert w.crit(F2) == [(0, 0)] and w.hess(F2, (0, 0)) == (2, 4, 2, -12) and w.kind(2, 4, 2) == "saddle"
# along y = -x the value is -2x^2 < 0, along y = x it is 6x^2 > 0: really not an extremum
assert w.same(F2.subs(Y, -X), -2 * X**2) and w.same(F2.subs(Y, X), 6 * X**2)

# ---------------------------------------------------------------- exam 24A-B-Q5a
Q = BANK["24A-B-Q5a"]
assert "(3-x)(3-y)(x+y-3)" in Q["question"].replace(" ", "")
F = (3 - X) * (3 - Y) * (X + Y - 3)
assert w.same(sp.diff(F, X), (3 - Y) * (6 - 2 * X - Y)) and w.same(sp.diff(F, Y), (3 - X) * (6 - X - 2 * Y))
PTS = w.crit(F)
assert PTS == [(0, 3), (2, 2), (3, 0), (3, 3)]
assert w.same(sp.diff(F, X, 2), 2 * Y - 6) and w.same(sp.diff(F, X, Y), 2 * X + 2 * Y - 9) \
    and w.same(sp.diff(F, Y, 2), 2 * X - 6)
H = {p: w.hess(F, p) for p in PTS}
assert H[(0, 3)] == (0, -3, -6, -9) and H[(3, 0)] == (-6, -3, 0, -9) and H[(3, 3)] == (0, 3, 0, -9)
assert H[(2, 2)] == (-2, -1, -2, 3) and w.kind(-2, -1, -2) == "max" and w.val(F, (2, 2)) == 1
assert all(w.kind(*H[p][:3]) == "saddle" for p in [(0, 3), (3, 0), (3, 3)])

