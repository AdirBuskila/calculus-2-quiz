t = sp.symbols("t", real=True)
# ---------------------------------------------------------------- three functions with Δ = 0 at the origin
G_MIN, G_MAX, G_NO = X**2 + Y**4, -X**2 - Y**4, X**2 - Y**4
for g in (G_MIN, G_MAX, G_NO):
    A, B, C, D = w.hess(g, (0, 0))
    assert (0, 0) in w.crit(g) and D == 0 and (A, B, C) in ((2, 0, 0), (-2, 0, 0))
# direct check: x^2 + y^4 >= 0 = f(0,0); -x^2 - y^4 <= 0; x^2 - y^4 takes both signs near 0
import numpy as np
_g = np.linspace(-1, 1, 41)
assert G_MIN.subs({X: 0, Y: 0}) == 0 and min(float(G_MIN.subs({X: a, Y: b})) for a in _g for b in _g) >= 0
assert max(float(G_MAX.subs({X: a, Y: b})) for a in _g for b in _g) <= 0
assert w.same(G_NO.subs({X: t, Y: 0}), t**2) and w.same(G_NO.subs({X: 0, Y: t}), -t**4)

# ---------------------------------------------------------------- exam 23A-C-Q5a
Q = BANK["23A-C-Q5a"]
assert "\\left(x^2-2y^2\\right)e^{x-y}" in Q["question"].replace(" ", "")
E = sp.exp(X - Y)
F = (X**2 - 2 * Y**2) * E
P1, P2 = X**2 + 2 * X - 2 * Y**2, -X**2 - 4 * Y + 2 * Y**2       # f_x = P1 e^{x-y}, f_y = P2 e^{x-y}
assert w.same(sp.diff(F, X), P1 * E) and w.same(sp.diff(F, Y), P2 * E)
assert w.same(P1 + P2, 2 * X - 4 * Y)                              # adding: 2x - 4y = 0, so x = 2y
assert w.same(P1.subs(X, 2 * Y), 2 * Y * (Y + 2))                  # 2y(y+2) = 0: y = 0 or y = -2
PTS = w.crit(F)
assert PTS == [(-4, -2), (0, 0)]
# at a critical point the bracket is 0, so only the bracket's own derivative survives:
#   A = (P1)_x e, B = (P1)_y e, C = (P2)_y e
for p in PTS:
    A, B, C, D = w.hess(F, p)
    e = E.subs({X: p[0], Y: p[1]})
    assert w.same(A, sp.diff(P1, X).subs({X: p[0], Y: p[1]}) * e)
    assert w.same(B, sp.diff(P1, Y).subs({X: p[0], Y: p[1]}) * e)
    assert w.same(C, sp.diff(P2, Y).subs({X: p[0], Y: p[1]}) * e)
H0 = w.hess(F, (0, 0))
assert H0 == (2, 0, -4, -8) and w.kind(*H0[:3]) == "saddle" and w.val(F, (0, 0)) == 0
e2 = sp.exp(-2)
H1 = w.hess(F, (-4, -2))
assert w.same(H1[0], -6 * e2) and w.same(H1[1], 8 * e2) and w.same(H1[2], -12 * e2) and w.same(H1[3], 8 * sp.exp(-4))
assert w.kind(*H1[:3]) == "max" and w.same(w.val(F, (-4, -2)), 8 * e2)

