m = sp.Symbol("m", real=True)

# ---------------------------------------------------------------- example 1: 2xy/(x²+3y²) along y = mx
F1 = 2 * x * y / (x ** 2 + 3 * y ** 2)
assert sp.simplify(F1.subs(y, m * x) - 2 * m / (1 + 3 * m ** 2)) == 0
assert W.along(F1, 0 * x) == 0 and W.along(F1, x) == sp.Rational(1, 2)

# ---------------------------------------------------------------- example 2: y³/(x²+y²): every line gives 0
F2 = y ** 3 / (x ** 2 + y ** 2)
assert sp.simplify(F2.subs(y, m * x) - m ** 3 * x / (1 + m ** 2)) == 0
assert all(W.along(F2, c * x) == 0 for c in (0, 1, -2, 5))
assert W.along_y(F2, 0 * y) == 0                                  # the y-axis x = 0

# ---------------------------------------------------------------- exam 24A-B-Q1a
Q = BANK["24A-B-Q1a"]
assert "x^2y^2" in Q["question"] and "x^6+y^3" in Q["question"]
FE = x ** 2 * y ** 2 / (x ** 6 + y ** 3)
assert sp.simplify(FE.subs(y, m * x) - m ** 2 * x / (x ** 3 + m ** 3)) == 0
assert all(W.along(FE, c * x) == 0 for c in (1, 2, -1, sp.Rational(1, 2)))
assert sp.simplify(FE.subs(y, 0)) == 0 and sp.simplify(FE.subs(x, 0)) == 0      # both axes: f = 0
assert sp.simplify(FE.subs(y, x ** 2)) == sp.Rational(1, 2)                     # the parabola: exactly 1/2
assert W.along(FE, x ** 2) == sp.Rational(1, 2)

