# ---------------------------------------------------------------- example 1: (x²y − 2y³)/(x²+y²) -> |f| <= 3r
F1 = (x ** 2 * y - 2 * y ** 3) / (x ** 2 + y ** 2)
p1, g1 = W.rpow(F1)
assert p1 == 1 and sp.simplify(g1 - (sp.cos(th) ** 2 * sp.sin(th) - 2 * sp.sin(th) ** 3)) == 0
assert W.sup_abs(g1) <= 3                                          # |cos²θ sinθ| + 2|sin³θ| <= 1 + 2

# ---------------------------------------------------------------- example 2: (x²−2y²)/(x²+3y²): r cancels
F2 = (x ** 2 - 2 * y ** 2) / (x ** 2 + 3 * y ** 2)
p2, g2 = W.rpow(F2)
assert p2 == 0
assert g2.subs(th, 0) == 1 and sp.simplify(g2.subs(th, sp.pi / 2)) == sp.Rational(-2, 3)

# ---------------------------------------------------------------- exam-style problem (original, bank={}):
# (2x⁴ − y⁴)/(x²+y²). The bank part 24S-A-Q2a (xy³/(x²+y²)) was dropped: it is the x<->y twin of the boss-quiz
# parts 24B-B-Q1b/c.
FE = (2 * x ** 4 - y ** 4) / (x ** 2 + y ** 2)
pe, ge = W.rpow(FE)
assert pe == 2 and sp.simplify(ge - (2 * sp.cos(th) ** 4 - sp.sin(th) ** 4)) == 0
assert W.sup_abs(ge) <= 3                                          # 2cos⁴θ <= 2, sin⁴θ <= 1
assert sp.simplify(FE.subs({x: h, y: 0}) - 2 * h ** 2) == 0 and sp.simplify(FE.subs({x: 0, y: h}) + h ** 2) == 0
assert W.pdef(FE, 0, "x") == 0 and W.pdef(FE, 0, "y") == 0       # 2h²/h = 2h -> 0,  −h²/h = −h -> 0
QE = W.Qexpr(FE, 0, 0, 0)
pq, gq = W.rpow(QE.subs({h: x, k: y}))
assert pq == 1 and sp.simplify(gq - ge) == 0                     # Q = r(2cos⁴θ − sin⁴θ), |Q| <= 3r

