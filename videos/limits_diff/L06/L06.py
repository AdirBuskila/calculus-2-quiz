# ---------------------------------------------------------------- example 1: (x³+4y³)/(x²+2y²), f(0,0)=0
F1 = (x ** 3 + 4 * y ** 3) / (x ** 2 + 2 * y ** 2)
assert sp.simplify(F1.subs({x: h, y: 0}) - h) == 0 and sp.simplify(F1.subs({x: 0, y: h}) - 2 * h) == 0
assert W.pdef(F1, 0, "x") == 1 and W.pdef(F1, 0, "y") == 2
_num, _den = sp.fraction(sp.together(sp.diff(F1, x)))
assert _num.subs({x: 0, y: 0}) == 0 and _den.subs({x: 0, y: 0}) == 0   # the formula's derivative at the origin: 0/0

# ---------------------------------------------------------------- example 2: (x²+y⁴)/(x²+y²), f(0,0)=0
F2 = (x ** 2 + y ** 4) / (x ** 2 + y ** 2)
assert sp.simplify(F2.subs({x: h, y: 0})) == 1                      # on the x-axis f = 1, but f(0,0) = 0
assert sp.limit(1 / h, h, 0, "+") == sp.oo                           # (1 − 0)/h: no limit, f_x(0,0) does not exist
assert sp.simplify(F2.subs({x: 0, y: h}) - h ** 2) == 0 and W.pdef(F2, 0, "y") == 0

# ---------------------------------------------------------------- exam 24B-B-Q1a: at (1, 0)
Q = BANK["24B-B-Q1a"]
assert "x^3y" in Q["question"] and "(1,0)" in Q["question"]
FE = x ** 3 * y / (x ** 2 + y ** 2)
FX = sp.diff(FE, x)
FY = sp.diff(FE, y)
assert sp.simplify(FX - (3 * x ** 2 * y * (x ** 2 + y ** 2) - 2 * x ** 4 * y) / (x ** 2 + y ** 2) ** 2) == 0
assert sp.simplify(FY - (x ** 3 * (x ** 2 + y ** 2) - 2 * x ** 3 * y ** 2) / (x ** 2 + y ** 2) ** 2) == 0
assert FX.subs({x: 1, y: 0}) == 0 and FY.subs({x: 1, y: 0}) == 1
# the same two numbers by the definition at (1, 0)
assert sp.simplify(FE.subs({x: 1 + h, y: 0})) == 0
assert sp.simplify(FE.subs({x: 1, y: h}) - h / (1 + h ** 2)) == 0
assert sp.limit((FE.subs({x: 1, y: h}) - 0) / h, h, 0) == 1
assert FE.subs({x: 1, y: 0}) == 0

