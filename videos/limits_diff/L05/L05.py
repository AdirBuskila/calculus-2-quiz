kk = sp.Symbol("k", real=True)

# ---------------------------------------------------------------- the three outcomes
F0 = x ** 4 * y / (x ** 8 + y ** 2)                          # L02: no limit at all
assert sp.simplify(F0.subs(y, kk * x ** 4) - kk / (1 + kk ** 2)) == 0
G = (sp.exp(x ** 2 + y ** 2) - 1) / (x ** 2 + y ** 2)           # u = x²+y² -> (e^u − 1)/u -> 1
assert sp.simplify(G.subs(x ** 2 + y ** 2, u) - (sp.exp(u) - 1) / u) == 0
assert sp.limit((sp.exp(u) - 1) / u, u, 0) == 1
assert W.along(G, 0 * x) == 1 and W.along(G, x) == 1 and W.along(G, x ** 2) == 1   # consistent with the limit 1

# ---------------------------------------------------------------- exam 22A-A-Q2b
Q = BANK["22A-A-Q2b"]
assert "\\sin\\dfrac{1}{\\sqrt{x^2+y^2}}" in Q["question"]
FE = (x ** 2 + y ** 2) * sp.sin(1 / sp.sqrt(x ** 2 + y ** 2))
assert sp.simplify(FE.subs({x: r * sp.cos(W.th), y: r * sp.sin(W.th)}) - r ** 2 * sp.sin(1 / r)) == 0
assert sp.limit(r ** 2 * sp.sin(1 / r), r, 0) == 0                  # |r² sin(1/r)| <= r²
assert sp.simplify(FE.subs({x: h, y: 0}) - h ** 2 * sp.sin(1 / sp.Abs(h))) == 0
assert sp.simplify(FE.subs({x: 0, y: h}) - h ** 2 * sp.sin(1 / sp.Abs(h))) == 0
assert sp.limit(h * sp.sin(1 / sp.Abs(h)), h, 0) == 0              # f_x(0,0) = f_y(0,0) = 0
assert W.pdef(FE, 0, "x") == 0 and W.pdef(FE, 0, "y") == 0
assert sp.limit(r * sp.sin(1 / r), r, 0) == 0                      # Q = r sin(1/r) -> 0
_t = np.logspace(-6, -1, 2000)
assert np.all(np.abs(_t * np.sin(1 / _t)) <= _t)                    # the bound used on screen, numerically too
_s = np.sin(1 / _t)
assert _s.max() > 0.99 and _s.min() < -0.99                         # sin(1/r) alone keeps swinging: no limit

