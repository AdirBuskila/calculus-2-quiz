kk, m, a = sp.symbols("k m a", real=True)

# ---------------------------------------------------------------- example: x⁴y/(x⁸+y²)
F1 = x ** 4 * y / (x ** 8 + y ** 2)
assert sp.simplify(F1.subs(y, m * x) - m * x ** 3 / (x ** 6 + m ** 2)) == 0
assert all(W.along(F1, c * x) == 0 for c in (1, -1, 3))
assert sp.solve(sp.Eq(4 + a, 2 * a), a) == [4]                    # numerator x^(4+a), denominator x^(2a) and x^8
assert sp.simplify(F1.subs(y, kk * x ** 4) - kk / (1 + kk ** 2)) == 0
assert W.along(F1, x ** 4) == sp.Rational(1, 2) and W.along(F1, 0 * x) == 0

# ---------------------------------------------------------------- the other variable: xy⁴/(x²+y⁸), x = ky⁴
F2 = x * y ** 4 / (x ** 2 + y ** 8)
assert all(W.along_y(F2, c * y) == 0 for c in (1, -2))
assert sp.simplify(F2.subs(x, kk * y ** 4) - kk / (1 + kk ** 2)) == 0
assert W.along_y(F2, y ** 4) == sp.Rational(1, 2)

# ---------------------------------------------------------------- exam 25A-A-Q1a
Q = BANK["25A-A-Q1a"]
assert "4x^3y" in Q["question"] and "3x^6+2y^2" in Q["question"]
FE = 4 * x ** 3 * y / (3 * x ** 6 + 2 * y ** 2)
assert sp.simplify(FE.subs(y, m * x) - 4 * m * x ** 2 / (3 * x ** 4 + 2 * m ** 2)) == 0
assert all(W.along(FE, c * x) == 0 for c in (1, -1, 2))
assert sp.solve(sp.Eq(3 + a, 2 * a), a) == [3]                    # numerator x^(3+a), denominator x^6 and x^(2a)
assert sp.simplify(FE.subs(y, kk * x ** 3) - 4 * kk / (3 + 2 * kk ** 2)) == 0
assert W.along(FE, x ** 3) == sp.Rational(4, 5) and W.along(FE, 0 * x) == 0
assert W.pdef(FE, 0, "x") == 0 and W.pdef(FE, 0, "y") == 0
assert sp.simplify(FE.subs({x: h, y: 0})) == 0 and sp.simplify(FE.subs({x: 0, y: h})) == 0

